"""
Diffraction Domain Models for ScoutRaider.
Defines Route segments, Presets, Solver inputs, and Solution plans.
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class ItinerarySegment(BaseModel):
    """
    A single geographical segment of a polygonalized route.
    """
    index: int
    distance: float = Field(..., ge=0.0, description="Segment distance in meters.")
    azimut: float = Field(default=0.0, ge=0.0, le=360.0, description="Bearing angle in degrees.")
    coords: List[List[float]] = Field(default_factory=list, description="[[lon, lat], ...]")
    poi_count: int = Field(default=0, ge=0)
    poi_density: float = Field(default=0.0, ge=0.0)
    poi_name: Optional[str] = None
    is_last_third: bool = False


class PresetConfig(BaseModel):
    """
    Diffraction Preset configuration defining target weights and module overrides.
    """
    id: str
    name: str
    description: Optional[str] = None
    weights: Dict[str, float] = Field(
        default_factory=dict,
        description="Relative appearance weights per module (0 = disabled)."
    )
    overrides: Dict[str, Dict[str, Any]] = Field(
        default_factory=dict,
        description="Preset-level overrides for specific modules (e.g. max_occurrences, max_proportion)."
    )


class StepAssignment(BaseModel):
    """
    Assignment of a module to one or more contiguous segments.
    """
    step_number: int
    module_id: str
    start_index: int
    segment_count: int
    distance_m: float
    azimut: float
    poi_info: Optional[str] = None
    fallback_used: bool = False


class DiffractionResult(BaseModel):
    """
    Full output generated by the diffraction solver.
    """
    itinerary_id: Optional[str] = None
    preset_used: str
    total_distance_m: float
    segment_count: int
    assignments: List[StepAssignment]
    module_counts: Dict[str, int]
    module_proportions: Dict[str, float]
    fallback_count: int = 0
    warnings: List[str] = Field(default_factory=list)
